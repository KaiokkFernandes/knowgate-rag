-- Portuguese stemming with accents stripped first. unaccent() as a function is only
-- STABLE and cannot be used in a generated column; as a dictionary inside the config,
-- to_tsvector(regconfig, text) stays IMMUTABLE.
-- Known limitation: accented stopwords ("são", "já") are unaccented before the stopword
-- check and are therefore kept as tokens.
CREATE TEXT SEARCH CONFIGURATION portuguese_unaccent (COPY = pg_catalog.portuguese);
ALTER TEXT SEARCH CONFIGURATION portuguese_unaccent
  ALTER MAPPING FOR hword, hword_part, word WITH unaccent, portuguese_stem;

