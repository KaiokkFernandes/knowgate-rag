import type { INestApplication } from '@nestjs/common';
import { Pool } from 'pg';
import request from 'supertest';
import type { App } from 'supertest/types';
import { buildPdf } from './fixtures/build-pdf';
import { createApp } from './setup/create-app';
import { registerUser, type TestUser } from './setup/users';

const MAX_UPLOAD_BYTES = 64 * 1024;

const POLICY_MD = [
  '# Política de reembolso',
  'Despesas de viagem são reembolsadas mediante nota fiscal.',
  '## Prazos',
  'O pedido deve ser feito em até 30 dias.',
].join('\n');

interface DocumentView {
  id: string;
  title: string;
  sourceType: string;
  visibility: string;
  status: string;
  teamIds: string[];
  chunkCount: number;
}

describe('Documents (integration)', () => {
  let app: INestApplication<App>;
  let pool: Pool;

  beforeAll(async () => {
    app = await createApp({
      AUTH_RATE_LIMIT_PER_MINUTE: '1000',
      UPLOAD_MAX_BYTES: String(MAX_UPLOAD_BYTES),
    });
    pool = new Pool({ connectionString: process.env.DATABASE_URL });
  });

  afterAll(async () => {
    await pool.end();
    await app.close();
  });

  const as = (user: TestUser) => {
    const auth = (r: request.Test) => r.set('Authorization', `Bearer ${user.token}`);
    const server = () => request(app.getHttpServer());
    return {
      get: (path: string) => auth(server().get(path)),
      post: (path: string, body?: object) => auth(server().post(path)).send(body),
      put: (path: string) => auth(server().put(path)),
      delete: (path: string) => auth(server().delete(path)),
      upload: (
        orgId: string,
        file: Buffer,
        fileName: string,
        fields: Record<string, string | string[]> = {},
      ) => {
        let req = auth(server().post(`/orgs/${orgId}/documents`));
        for (const [name, value] of Object.entries(fields)) {
          for (const item of Array.isArray(value) ? value : [value]) req = req.field(name, item);
        }
        return req.attach('file', file, fileName);
      },
    };
  };

  async function createOrg(owner: TestUser): Promise<string> {
    const response = await as(owner).post('/orgs', { name: 'Acme' }).expect(201);
    return (response.body as { id: string }).id;
  }

  async function addMember(admin: TestUser, orgId: string, user: TestUser) {
    await as(admin).post(`/orgs/${orgId}/members`, { email: user.email }).expect(201);
  }

  async function createTeam(admin: TestUser, orgId: string, name: string): Promise<string> {
    const response = await as(admin).post(`/orgs/${orgId}/teams`, { name }).expect(201);
    return (response.body as { id: string }).id;
  }

  async function documentCount(orgId: string): Promise<number> {
    const { rows } = await pool.query<{ count: string }>(
      'SELECT count(*) FROM "Document" WHERE "organizationId" = $1',
      [orgId],
    );
    return Number(rows[0]?.count);
  }

  describe('upload', () => {
    it('stores a Markdown document and its chunks, PENDING until the worker embeds them', async () => {
      const admin = await registerUser(app);
      const orgId = await createOrg(admin);

      const response = await as(admin)
        .upload(orgId, Buffer.from(POLICY_MD), 'Política de reembolso.md')
        .expect(201);
      const document = response.body as DocumentView;

      expect(document).toMatchObject({
        // UTF-8 file name preserved (defParamCharset), extension removed.
        title: 'Política de reembolso',
        sourceType: 'MARKDOWN',
        visibility: 'ORG',
        status: 'PENDING',
        teamIds: [],
        chunkCount: 2, // one per Markdown section
      });

      const { rows } = await pool.query<{
        organizationId: string;
        reference: string;
        matchesSearch: boolean;
      }>(
        `SELECT "organizationId", reference,
                "searchVector" @@ plainto_tsquery('portuguese_unaccent', 'politica reembolsadas') AS "matchesSearch"
           FROM "Chunk" WHERE "documentId" = $1 ORDER BY position`,
        [document.id],
      );
      // Tenant copied to the chunk; full-text vector generated by the database.
      // (Embeddings are covered by embeddings.int-spec.ts: the worker runs right after upload.)
      expect(rows).toEqual([
        {
          organizationId: orgId,
          reference: 'Política de reembolso',
          matchesSearch: true, // accent-insensitive and stemmed: "politica", "reembolsadas"
        },
        {
          organizationId: orgId,
          reference: 'Política de reembolso > Prazos',
          matchesSearch: false,
        },
      ]);
    });

    it('cites PDF pages', async () => {
      const admin = await registerUser(app);
      const orgId = await createOrg(admin);
      const pdf = buildPdf([['Manual de seguranca'], ['Senhas com 12 caracteres']]);

      const response = await as(admin)
        .upload(orgId, pdf, 'manual.pdf', { title: 'Manual de segurança' })
        .expect(201);
      const document = response.body as DocumentView;

      const { rows } = await pool.query<{ reference: string }>(
        'SELECT reference FROM "Chunk" WHERE "documentId" = $1 ORDER BY position',
        [document.id],
      );
      expect(document).toMatchObject({ title: 'Manual de segurança', sourceType: 'PDF' });
      expect(rows.map((row) => row.reference)).toEqual(['p. 1', 'p. 2']);
    });

    it.each([
      ['no file', undefined, undefined, 400],
      ['an unsupported extension', Buffer.from('a,b'), 'data.csv', 415],
      ['a binary renamed to .pdf', Buffer.from('MZ\x90\x00binary'), 'invoice.pdf', 415],
      ['a PDF without text (scan)', buildPdf([[]]), 'scan.pdf', 422],
      ['a corrupted PDF', Buffer.from('%PDF-1.4 garbage'), 'broken.pdf', 422],
      ['a file over the size limit', Buffer.alloc(MAX_UPLOAD_BYTES + 1, 'a'), 'big.txt', 413],
    ])('rejects %s without storing anything', async (_case, file, fileName, status) => {
      const admin = await registerUser(app);
      const orgId = await createOrg(admin);

      const req = file
        ? as(admin).upload(orgId, file, fileName ?? '')
        : as(admin).post(`/orgs/${orgId}/documents`);
      await req.expect(status);

      expect(await documentCount(orgId)).toBe(0);
    });

    it('only lets admins upload (403 for members, 404 for outsiders)', async () => {
      const admin = await registerUser(app);
      const member = await registerUser(app);
      const outsider = await registerUser(app);
      const orgId = await createOrg(admin);
      await addMember(admin, orgId, member);

      await as(member).upload(orgId, Buffer.from('x'), 'a.txt').expect(403);
      await as(outsider).upload(orgId, Buffer.from('x'), 'a.txt').expect(404);
      expect(await documentCount(orgId)).toBe(0);
    });

    it('validates visibility and teams', async () => {
      const admin = await registerUser(app);
      const orgId = await createOrg(admin);
      const teamId = await createTeam(admin, orgId, 'RH');
      const otherAdmin = await registerUser(app);
      const otherOrgTeam = await createTeam(otherAdmin, await createOrg(otherAdmin), 'RH');
      const file = Buffer.from('Conteúdo');

      // TEAMS without teams, ORG with teams, a team of another organization.
      await as(admin).upload(orgId, file, 'a.txt', { visibility: 'TEAMS' }).expect(400);
      await as(admin).upload(orgId, file, 'a.txt', { teamIds: teamId }).expect(400);
      await as(admin)
        .upload(orgId, file, 'a.txt', { visibility: 'TEAMS', teamIds: otherOrgTeam })
        .expect(400);
      expect(await documentCount(orgId)).toBe(0);
    });
  });

  describe('personal data', () => {
    it('masks CPF, CNPJ, e-mail and phone before storing (nothing raw reaches the database)', async () => {
      const admin = await registerUser(app);
      const orgId = await createOrg(admin);
      // Test values (valid check digits, not real people or companies).
      const raw = ['529.982.247-25', '11.222.333/0001-81', 'joana@acme.test', '(11) 98765-4321'];
      const markdown = `# Contato de joana@acme.test\nCPF ${raw[0]}, CNPJ ${raw[1]}, e-mail ${raw[2]}, tel. ${raw[3]}.`;

      const document = (
        await as(admin).upload(orgId, Buffer.from(markdown), 'Ficha 529.982.247-25.md').expect(201)
      ).body as DocumentView;

      const { rows } = await pool.query<{ content: string; reference: string; title: string }>(
        `SELECT c.content, c.reference, d.title
           FROM "Chunk" c JOIN "Document" d ON d.id = c."documentId"
          WHERE c."documentId" = $1`,
        [document.id],
      );
      expect(rows).toHaveLength(1);
      expect(rows[0]?.content).toBe(
        '# Contato de [EMAIL]\nCPF [CPF], CNPJ [CNPJ], e-mail [EMAIL], tel. [TELEFONE].',
      );
      expect(rows[0]?.reference).toBe('Contato de [EMAIL]');
      expect(rows[0]?.title).toBe('Ficha [CPF]');
      const stored = JSON.stringify(rows);
      for (const value of raw) expect(stored).not.toContain(value);
    });
  });

  describe('visibility', () => {
    it('shows TEAMS documents only to members of the listed teams', async () => {
      const admin = await registerUser(app);
      const hrMember = await registerUser(app);
      const outsider = await registerUser(app);
      const orgId = await createOrg(admin);
      await addMember(admin, orgId, hrMember);
      await addMember(admin, orgId, outsider);
      const hr = await createTeam(admin, orgId, 'RH');
      const finance = await createTeam(admin, orgId, 'Financeiro');
      await as(admin).put(`/orgs/${orgId}/teams/${hr}/members/${hrMember.id}`).expect(204);

      const shared = (
        await as(admin).upload(orgId, Buffer.from('Para todos'), 'geral.txt').expect(201)
      ).body as DocumentView;
      const restricted = (
        await as(admin)
          .upload(orgId, Buffer.from('Salários'), 'salarios.txt', {
            visibility: 'TEAMS',
            teamIds: [hr, finance], // repeated multipart field
          })
          .expect(201)
      ).body as DocumentView;
      expect([...restricted.teamIds].sort()).toEqual([hr, finance].sort());

      const titles = async (user: TestUser) =>
        ((await as(user).get(`/orgs/${orgId}/documents`).expect(200)).body as DocumentView[])
          .map((d) => d.title)
          .sort();

      expect(await titles(admin)).toEqual(['geral', 'salarios']);
      expect(await titles(hrMember)).toEqual(['geral', 'salarios']);
      expect(await titles(outsider)).toEqual(['geral']);

      await as(outsider).get(`/orgs/${orgId}/documents/${restricted.id}`).expect(404);
      await as(hrMember).get(`/orgs/${orgId}/documents/${restricted.id}`).expect(200);
      await as(outsider).get(`/orgs/${orgId}/documents/${shared.id}`).expect(200);
    });

    it('never exposes a document through another organization route', async () => {
      const adminA = await registerUser(app);
      const adminB = await registerUser(app);
      const orgA = await createOrg(adminA);
      const orgB = await createOrg(adminB);
      const document = (await as(adminA).upload(orgA, Buffer.from('Segredo'), 'a.txt').expect(201))
        .body as DocumentView;

      // B is admin of its own org, but the document id belongs to A.
      await as(adminB).get(`/orgs/${orgB}/documents/${document.id}`).expect(404);
      await as(adminB).delete(`/orgs/${orgB}/documents/${document.id}`).expect(404);
      expect(await documentCount(orgA)).toBe(1);
    });
  });

  describe('delete', () => {
    it('lets admins delete a document with its chunks', async () => {
      const admin = await registerUser(app);
      const member = await registerUser(app);
      const orgId = await createOrg(admin);
      await addMember(admin, orgId, member);
      const document = (await as(admin).upload(orgId, Buffer.from(POLICY_MD), 'p.md').expect(201))
        .body as DocumentView;

      await as(member).delete(`/orgs/${orgId}/documents/${document.id}`).expect(403);
      await as(admin).delete(`/orgs/${orgId}/documents/${document.id}`).expect(204);
      await as(admin).get(`/orgs/${orgId}/documents/${document.id}`).expect(404);

      const { rows } = await pool.query<{ count: string }>(
        'SELECT count(*) FROM "Chunk" WHERE "documentId" = $1',
        [document.id],
      );
      expect(Number(rows[0]?.count)).toBe(0);
    });
  });
});
